#!/usr/bin/env python3
"""Splice web/fun_facts.json into web/shell.html as the MALL_FACTS array.

The web export copies only index.html/.js/.wasm, so the facts must live inside the shell.
Edit web/fun_facts.json (store, text, source), then run:  python3 tools/facts_to_shell.py
The load screen (first open and every wing crossing) shows one fact at random and
rotates every few seconds. Run from the project folder.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FACTS = os.path.join(ROOT, "web", "fun_facts.json")
SHELL = os.path.join(ROOT, "web", "shell.html")
START = "// MALL_FACTS start (generated by tools/facts_to_shell.py from web/fun_facts.json)"
END = "// MALL_FACTS end"

facts = json.load(open(FACTS, encoding="utf-8"))
rows = []
for f in facts:
    if not f.get("text"):
        continue
    rows.append(json.dumps({"s": f.get("store", ""), "t": f["text"]}, ensure_ascii=False))
block = START + "\nconst MALL_FACTS = [\n" + ",\n".join(rows) + "\n];\n" + END

html = open(SHELL, encoding="utf-8").read()
pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
if not pat.search(html):
    print("markers not found in web/shell.html", file=sys.stderr)
    sys.exit(1)
html = pat.sub(lambda m: block, html)
open(SHELL, "w", encoding="utf-8").write(html)
print(f"wrote {len(rows)} facts into web/shell.html")
